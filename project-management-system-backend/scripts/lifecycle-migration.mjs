// Writes migrations/0026_omnicontact_lifecycle.sql from src/data/lifecycleTemplates.js, so the stored template is
// exactly the one the code and tests know. Run: npx vite-node scripts/lifecycle-migration.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { cleanTemplate } from "../../project-management-system-frontend/src/data/lifecycle.js";
import { OMNICONTACT_NAME, omnicontactLifecycle } from "../../project-management-system-frontend/src/data/lifecycleTemplates.js";

const ID = "0a1fec7c1e000016"; // Omnicontact's template (16 hex characters, as the API's routes expect)
const def = cleanTemplate(omnicontactLifecycle());
const q = (/** @type {unknown} */ v) => (v == null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const stages = def.stages
  .map((s, i) => `  (${q(s.code)}, ${q(s.name)}, ${q(s.phase)}, ${q(def.phases.find((p) => p.code === s.phase)?.name)}, ${i + 1}, ${q(s.type)}, ${q(s.targetDays)}, ${s.weight})`)
  .join(",\n");

const sql = `-- Omnicontact's default project lifecycle (16 stages; docs/lifecycle-plan.md, docs/design/lifecycle-mapping-dry-run.md).
-- GENERATED by scripts/lifecycle-migration.mjs from src/data/lifecycleTemplates.js: change that file, not this one.
--   1. lifecycle_map_projects(organisation, template): puts every project of the organisation that has no lifecycle
--      on the template, at the stage the rules give (the same rules as src/data/lifecycle.js mapExistingProject,
--      tested against each other in tests/lifecycle.migration.test.js). A project the rules can't place is left
--      without a lifecycle and reported (flagged, never guessed). Earlier stages aren't re-checked: the history says
--      "migrated". The one correction: a project delivered at 100% but still marked Testing becomes Live.
--   2. Omnicontact gets its template (published, its default) and its projects are mapped.
-- Reverse: migrations/down/0026_omnicontact_lifecycle.down.sql.

CREATE FUNCTION lifecycle_map_projects(p_org TEXT, p_template TEXT)
RETURNS TABLE (system_id TEXT, name TEXT, status TEXT, stage TEXT, why TEXT) LANGUAGE plpgsql AS $$
DECLARE
  r      RECORD;
  sig    JSONB;
  n      INTEGER;
  ok     INTEGER;
  dec    INTEGER;
  st     TEXT;
  closed BOOLEAN;
  reason TEXT;
  fix    TEXT;
  at     TEXT := to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
BEGIN
  FOR r IN
    SELECT s.id, s.organization_id, s.workspace_id, s.data::jsonb AS d
    FROM systems s
    WHERE s.organization_id = p_org AND NOT EXISTS (SELECT 1 FROM project_lifecycle l WHERE l.system_id = s.id)
    ORDER BY s.sort, s.rowid
  LOOP
    sig := CASE WHEN jsonb_typeof(r.d->'pcn'->'signatories') = 'array' THEN r.d->'pcn'->'signatories' ELSE '[]'::jsonb END;
    n := jsonb_array_length(sig);
    SELECT COUNT(*) FILTER (WHERE x->>'status' = 'APPROVED'), COUNT(*) FILTER (WHERE x->>'status' = 'DECLINED') INTO ok, dec FROM jsonb_array_elements(sig) x;
    st := NULL; closed := FALSE; fix := NULL;
    CASE r.d->>'status'
      WHEN 'IDEA' THEN
        IF r.d->'pcn' IS NULL OR n = 0 THEN st := 'PCN_DRAFT'; reason := CASE WHEN r.d->'pcn' IS NULL THEN 'Idea, no Concept Note yet' ELSE 'Concept Note started, no signatories yet' END;
        ELSIF dec > 0 THEN st := 'PCN_DRAFT'; reason := 'Concept Note declined';
        ELSIF ok < n THEN st := 'PCN_SIGNOFF'; reason := format('Concept Note waiting for signatures (%s/%s)', ok, n);
        ELSE st := 'DISCOVERY'; reason := 'Concept Note fully signed';
        END IF;
      WHEN 'UPCOMING' THEN
        IF r.d->'pcn' IS NOT NULL AND n > 0 AND ok = n THEN st := 'DISCOVERY'; reason := 'Concept Note signed, not started';
        ELSE st := 'PCN_DRAFT'; reason := 'Upcoming without a Concept Note: it starts with one';
        END IF;
      WHEN 'WIP' THEN st := 'DEV'; reason := 'In progress';
      WHEN 'TESTING' THEN
        IF COALESCE(r.d->>'finishedAt', '') <> '' AND COALESCE((r.d->>'progress')::numeric, 0) >= 100 THEN
          st := 'CLOSE'; closed := TRUE; fix := 'LIVE'; reason := 'Marked Testing but delivered at 100%: closed, status corrected to Live';
        ELSE st := 'QAT'; reason := 'Testing';
        END IF;
      WHEN 'TO_DEPLOY' THEN st := 'DEPLOY'; reason := 'Ready to deploy';
      WHEN 'LIVE' THEN st := 'CLOSE'; closed := TRUE; reason := 'Live';
      WHEN 'COMPLETED' THEN st := 'CLOSE'; closed := TRUE; reason := 'Completed';
      ELSE st := NULL; reason := format('Unknown status %s: flagged, not mapped', r.d->>'status');
    END CASE;
    system_id := r.id; name := r.d->>'name'; status := r.d->>'status'; stage := st; why := reason;
    RETURN NEXT;
    CONTINUE WHEN st IS NULL;
    INSERT INTO project_lifecycle (organization_id, workspace_id, system_id, template_id, stage_code, stage_entered_at, state, migrated)
    VALUES (r.organization_id, r.workspace_id, r.id, p_template, st, at, CASE WHEN closed THEN 'closed' ELSE 'active' END, 1);
    INSERT INTO project_stage_history (organization_id, workspace_id, system_id, from_code, to_code, kind, reason, evidence, by_id, by_name, at)
    VALUES (r.organization_id, r.workspace_id, r.id, NULL, st, 'migrate', reason,
            jsonb_build_object('status', r.d->>'status', 'progress', r.d->'progress', 'note', 'Earlier stages: gate evidence not on record')::text, NULL, 'Migration 0026', at);
    IF fix IS NOT NULL THEN
      UPDATE systems SET data = jsonb_set(data::jsonb, '{status}', to_jsonb(fix))::text WHERE id = r.id;
    END IF;
  END LOOP;
END $$;
REVOKE EXECUTE ON FUNCTION lifecycle_map_projects(TEXT, TEXT) FROM PUBLIC;

-- 2. Omnicontact (nothing happens where there is no Omnicontact, such as a fresh test database).
INSERT INTO lifecycle_templates (id, organization_id, workspace_id, family_id, version, status, is_default, name, definition, created_at, published_at)
SELECT ${q(ID)}, o.id, NULL, ${q(ID)}, 1, 'published', 1, ${q(OMNICONTACT_NAME)}, ${q(JSON.stringify(def))},
       to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'), to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
FROM organizations o WHERE o.code = 'omnicontact';
INSERT INTO lifecycle_stages (organization_id, template_id, code, name, phase_code, phase_name, position, type, target_days, weight)
SELECT t.organization_id, t.id, v.code, v.name, v.phase_code, v.phase_name, v.position, v.type, v.target_days, v.weight
FROM lifecycle_templates t, (VALUES
${stages}
) AS v (code, name, phase_code, phase_name, position, type, target_days, weight)
WHERE t.id = ${q(ID)};
SELECT * FROM lifecycle_map_projects((SELECT id FROM organizations WHERE code = 'omnicontact'), ${q(ID)})
WHERE EXISTS (SELECT 1 FROM lifecycle_templates WHERE id = ${q(ID)});
`;
const out = fileURLToPath(new URL("../database/migrations/0026_omnicontact_lifecycle.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`wrote ${out} (${def.stages.length} stages)`);
