/**
 * Emoji matching a search: every word must appear in its search words.
 * @param {string} q
 * @returns {string[]}
 */
export function searchEmoji(q) {
  const words = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const seen = /** @type {Set<string>} */ (/** @type {unknown} */ (new Set()));
  /** @type {string[]} */ const out = [];
  for (const g of EMOJI_GROUPS)
    for (const [e, kw] of g.emoji)
      if (!seen.has(e) && words.every((w) => kw.includes(w))) {
        seen.add(e);
        out.push(e);
      }
  return out;
}
